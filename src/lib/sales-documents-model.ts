/** Pure model for Sales proposals, RFPs and RFQs (client + server). */
import { sowServicesBody } from "./agreement-templates";
export type DocKind = "proposal" | "rfp" | "rfq";
export type DocDirection = "response" | "outbound";
export type Section = { key: string; title: string; body: string; question?: string | null; included?: boolean | undefined };

/** Sections reps switch on only when needed. Off by default on new documents; older saved sections without the flag stay shown. */
export const OPTIONAL_SECTION_KEYS = ["needs", "approach", "timeline", "next", "about"];
export const isSectionShown = (s: { key: string; included?: boolean | undefined }) => !OPTIONAL_SECTION_KEYS.includes(s.key) || s.included !== false;

export const KIND_LABEL: Record<DocKind, string> = { proposal: "Proposal", rfp: "RFP", rfq: "RFQ" };
export const DIRECTION_LABEL: Record<DocDirection, string> = { response: "Response to prospect", outbound: "Request to vendor" };

export const RESPONSE_STATUSES = ["draft", "with_marketing", "submitted", "approved", "sent", "won", "lost", "declined"] as const;
export const OUTBOUND_STATUSES = ["draft", "with_marketing", "submitted", "approved", "sent", "responses_received", "awarded"] as const;
export const STATUS_LABEL: Record<string, string> = {
  draft: "Draft", with_marketing: "With Marketing", submitted: "Waiting for approval", approved: "Approved", sent: "Sent",
  won: "Won", lost: "Lost", declined: "Declined", responses_received: "Responses received", awarded: "Awarded",
};
/** Outcomes a rep may record after sending. */
export const OUTCOMES: Record<DocDirection, string[]> = { response: ["won", "lost", "declined"], outbound: ["responses_received", "awarded"] };

export const SALES_DOC_ROLES = ["sales", "account_executive", "bdr", "sales_management", "cro", "executive", "super_admin", "leadership"];
export const SALES_DOC_APPROVERS = ["sales_management", "cro"];
export const MARKETING_HELPERS = ["marketing_manager", "marketing_specialist"];

export function defaultSections(kind: DocKind, direction: DocDirection): Section[] {
  const s = (key: string, title: string): Section => ({ key, title, body: "" });
  if (direction === "outbound") return [s("overview", "Overview"), s("scope", "Scope of work"), s("requirements", "Requirements"), s("timeline", "Timeline"), s("submission", "How to respond"), s("evaluation", "Evaluation criteria")];
  if (kind === "rfq") return [s("summary", "Summary"), s("pricing", "Pricing"), s("terms", "Terms"), s("about", "About Harmonious")];
  const o = (key: string, title: string): Section => ({ key, title, body: "", included: false });
  return [s("summary", "Executive summary"), o("needs", "Your needs"), o("approach", "Our approach"), s("services", "Services and pricing"), o("timeline", "Timeline"), o("about", "About Harmonious"), o("next", "Next steps")];
}

export const sectionsText = (sections: Section[]) =>
  sections.map((s) => `${s.title}\n${s.question ? `Question: ${s.question}\n` : ""}${s.body}`.trim()).join("\n\n");

/** Fallback About Harmonious wording, used only until a Super Admin saves the controlled version. */
export const ABOUT_HARMONIOUS =
  "Harmonious is a fund administration and back-office platform for venture funds, SPVs and their investors. Our services span fund setup, investor onboarding and KYC, accounting and NAV, K-1 tax, regulatory filings, banking and cap tables.\n\nWe help fund teams coordinate administrative workflows and investor-related operations, with every engagement tailored to the services agreed during scoping.\n\nLearn more at harmonious.co.";

export type MsaFacts = { version: string; effectiveDate: string | null; sections: { section_no: string; title: string; body: string }[] } | null;
export const NO_MSA_TERMS = "Terms will be provided in the Master Services Agreement.";
export const termsTitle = (msa: MsaFacts) => msa ? "Terms — Master Services Agreement" : "Terms";

export type LockFacts = { msa?: MsaFacts; about?: string | null; organization: string | null; contactName: string | null; lines: { label: string; quantity: number; unit_cents: number; line_cents: number; billing_frequency?: string | null; service_details?: { scope?: string; included?: string[]; excluded?: string[] } | null }[] };

/** Sections whose text is generated by the platform and can't be edited (responses to prospects only). */
export function lockedKeys(kind: DocKind, direction: DocDirection): string[] {
  if (direction !== "response") return [];
  return kind === "rfq" ? ["summary", "pricing", "terms", "about"] : ["summary", "needs", "approach", "services", "terms", "about"];
}

/** "Your needs", generated from the services on the quote. */
export function needsText(f: LockFacts): string {
  const names = selectedServiceLabels(f.lines).map(cleanLabel);
  if (!names.length) return "Your needs will appear here once services are added to the quote.";
  return [`${f.organization || "Your organization"} is looking for support with:`, ...names.map((n) => `- ${n}`)].join("\n");
}

/** "Our approach" is standard Harmonious wording, listing the services being quoted. */
export function approachText(f: LockFacts): string {
  const names = selectedServiceLabels(f.lines).map(cleanLabel);
  return [
    "Harmonious delivers every engagement through one standard process:",
    "1. Kickoff: we confirm scope, contacts and timelines, and collect the documents we need.",
    `2. Setup: we configure ${names.length ? names.join(", ") : "the agreed services"} on the Harmonious platform.`,
    "3. Review: your team reviews and approves key outputs before anything is finalized.",
    "4. Ongoing service: our team runs each service on its agreed schedule, with status visible in your portal.",
    "5. Support: questions go to your Harmonious team through the portal inbox.",
  ].join("\n");
}

const money = (c: number) => `$${(Number(c) / 100).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const FREQ_WORD: Record<string, string> = { one_time: "one-time", monthly: "per month", quarterly: "per quarter", annual: "per year" };

export const SUMMARY_NOTE_TITLE = "Note from your Harmonious contact";
export const SUMMARY_NOTE_MAX = 300;

const cleanLabel = (s: string) => s.replace(/\s*\((annual|quarterly|monthly|one[- ]time)\)\s*$/i, "").trim();

const FREQ_ORDER = ["one_time", "monthly", "quarterly", "annual"];
const PER_YEAR: Record<string, number> = { monthly: 12, quarterly: 4, annual: 1 };
const TOTAL_WORD: Record<string, string> = { one_time: "One-time total", monthly: "Monthly total", quarterly: "Quarterly total", annual: "Annual total" };

const PER_MONTH: Record<string, number> = { monthly: 1, quarterly: 1 / 3, annual: 1 / 12 };
const BILLED_EVERY: Record<string, string> = { monthly: "every month", quarterly: "every 3 months", annual: "once a year" };
const BILLED_WORD: Record<string, string> = { monthly: "monthly", quarterly: "quarterly", annual: "annually" };

/** Client-friendly pricing: recurring services shown as a monthly rate, plus what is actually billed and when. */
export function pricingText(lines: LockFacts["lines"]): string {
  if (!lines.length) return "Pricing will appear here once services are added to the quote.";
  const freqOf = (l: LockFacts["lines"][number]) => (l.billing_frequency && FREQ_WORD[l.billing_frequency] ? l.billing_frequency : "one_time");
  const recurring = lines.filter((l) => freqOf(l) !== "one_time");
  const oneTime = lines.filter((l) => freqOf(l) === "one_time");
  const monthlyOf = (l: LockFacts["lines"][number]) => Math.round(Number(l.line_cents || 0) * PER_MONTH[freqOf(l)]!);
  const out: string[] = [];
  if (recurring.length) {
    const monthly = recurring.reduce((s, l) => s + monthlyOf(l), 0);
    out.push(`Your monthly rate: ${money(monthly)} per month`);
    const by: Record<string, number> = {};
    for (const l of recurring) by[freqOf(l)] = (by[freqOf(l)] ?? 0) + Number(l.line_cents || 0);
    for (const f of ["monthly", "quarterly", "annual"]) if (by[f] !== undefined) out.push(`Billed ${BILLED_WORD[f]}: ${money(by[f]!)} ${BILLED_EVERY[f]}`);
    out.push("");
    out.push("What's included:");
    for (const l of recurring) out.push(`- ${cleanLabel(l.label)}${Number(l.quantity) > 1 ? ` (x${l.quantity})` : ""}: ${money(monthlyOf(l))} per month, billed ${money(Number(l.line_cents))} ${BILLED_WORD[freqOf(l)]}`);
  }
  if (oneTime.length) {
    if (out.length) out.push("");
    const total = oneTime.reduce((s, l) => s + Number(l.line_cents || 0), 0);
    out.push(`One-time fees: ${money(total)}, billed once when you sign`);
    for (const l of oneTime) out.push(`- ${cleanLabel(l.label)}${Number(l.quantity) > 1 ? ` (x${l.quantity})` : ""}: ${money(Number(l.line_cents))}`);
  }
  out.push("");
  out.push("How to get started: accept this proposal, sign the MSA and SOW we send you, and your first invoice follows. You can pay each invoice online by card.");
  out.push("(Pricing from the approved quote.)");
  return out.join("\n");
}

export function termsText(msa: MsaFacts | undefined): string {
  if (!msa || !msa.sections.length) return NO_MSA_TERMS;
  const head = "These terms are the Harmonious Master Services Agreement.";
  return [head, ...msa.sections.map((x) => `${x.section_no}. ${x.title}\n${x.body.trim()}`)].join("\n\n");
}

export function summaryText(f: LockFacts): string {
  const services = f.lines.map((l) => cleanLabel(l.label));
  const list = services.length <= 1 ? services[0] ?? "fund administration services" : `${services.slice(0, -1).join(", ")} and ${services[services.length - 1]}`;
  return `Harmonious proposes ${list} for ${f.organization || "your organization"}${f.contactName ? `, prepared for ${f.contactName}` : ""}.`;
}

/** Overwrites controlled sections with platform text; strips typed prices from editable sections. */
export function applyLockedSections(kind: DocKind, direction: DocDirection, sections: Section[], f: LockFacts): Section[] {
  const keys = lockedKeys(kind, direction);
  if (!keys.length) return sections;
  const gen: Record<string, string> = { summary: summaryText(f), needs: needsText(f), approach: approachText(f), pricing: pricingText(f.lines), terms: termsText(f.msa), about: f.about || ABOUT_HARMONIOUS };
  const out = sections.map((s) => {
    // Services and pricing mirror the SOW exactly: same service wording, same billed amounts.
    if (kind !== "rfq" && s.key === "services") return { ...s, title: "Services and pricing (Statement of Work)", body: `${servicesFromSow(f.lines)}\n\n${pricingText(f.lines)}`.trim() };
    if (keys.includes(s.key)) return { ...s, ...(s.key === "terms" ? { title: termsTitle(f.msa ?? null) } : {}), body: gen[s.key] ?? s.body };
    if (kind !== "rfq" && s.key === "services") {
      const typed = s.body.split(SOW_MARK)[0]!.split("\n").filter((l) => !/\$\s?[\d,]/.test(l) && !/^\s*Total:/i.test(l) && !/Pricing from the approved quote/i.test(l)).join("\n").trim();
      return { ...s, body: `${typed}\n\n${servicesFromSow(f.lines)}\n\n${pricingText(f.lines)}`.trim() };
    }
    return s;
  });
  // Reps may add one short note under the summary; it's editable and still goes through approval.
  if (keys.includes("summary")) {
    const idx = out.findIndex((s) => s.key === "summary_note");
    const note = idx >= 0 ? { ...out.splice(idx, 1)[0]!, title: SUMMARY_NOTE_TITLE } : { key: "summary_note", title: SUMMARY_NOTE_TITLE, body: "" };
    note.body = note.body.replace(/\s+/g, " ").trim().slice(0, SUMMARY_NOTE_MAX);
    const at = out.findIndex((s) => s.key === "summary");
    out.splice(at >= 0 ? at + 1 : 0, 0, note);
  }
  const TITLES: Record<string, string> = { about: "About Harmonious", pricing: "Pricing", needs: "Your needs", approach: "Our approach", summary: "Summary" };
  for (const k of keys) if (!out.some((s) => s.key === k)) {
    if (k === "services") { const a = out.findIndex((x) => x.key === "about"); out.splice(a >= 0 ? a : out.length, 0, { key: "services", title: "Services and pricing (Statement of Work)", body: `${servicesFromSow(f.lines)}\n\n${pricingText(f.lines)}`.trim() }); continue; }
    if ((k === "needs" || k === "approach") && kind === "rfq") continue;
    out.push({ key: k, title: k === "terms" ? termsTitle(f.msa ?? null) : TITLES[k] ?? "Summary", body: gen[k] ?? "", ...(OPTIONAL_SECTION_KEYS.includes(k) ? { included: false } : {}) });
  }
  // RFQs list the SOW services right before pricing.
  if (kind === "rfq") {
    const svc = { key: "services", title: "Services (Statement of Work)", body: servicesFromSow(f.lines) };
    const i = out.findIndex((s) => s.key === "services");
    if (i >= 0) out[i] = svc; else { const p = out.findIndex((s) => s.key === "pricing"); out.splice(p >= 0 ? p : out.length, 0, svc); }
  }
  return aboutLast(out);
}

const SOW_MARK = "Services from your Statement of Work:";
/** Services described with the same wording as the SOW the client signs; falls back to the service name. */
export function servicesFromSow(lines: { label: string; description?: string | null; service_details?: { scope?: string; included?: string[]; excluded?: string[] } | null }[]): string {
  const labels = selectedServiceLabels(lines);
  if (!labels.length) return `${SOW_MARK}\nServices will appear here once they are added to the quote.`;
  const services = labels.map((label) => {
    const line = lines.find((l) => l.label === label);
    const d = line?.service_details ?? null;
    return { label: cleanLabel(label), description: line?.description ?? null, scope: d?.scope ?? null, included: d?.included ?? null, excluded: d?.excluded ?? null };
  });
  return `${SOW_MARK}\n${sowServicesBody(services).replace(" for the vehicle named above", "")}`;
}

/** About Harmonious always closes the document, after services, pricing and totals. */
export const aboutLast = <T extends { key: string }>(sections: T[]): T[] => [...sections.filter((s) => s.key !== "about"), ...sections.filter((s) => s.key === "about")];

/** The standard proposal/quote email. Empty rep messages are left out. */
export function proposalReadyEmail(d: { clientName?: string | null; repMessage?: string | null; repName?: string | null; link: string; canSign: boolean; signerNames?: string[] }) {
  const name = d.clientName?.trim() || "there";
  const msg = d.repMessage?.trim() ?? "";
  const rep = d.repName?.trim() || "Harmonious Sales";
  const viewOnly = d.canSign ? "" : `This copy is for your review. ${(d.signerNames ?? []).join(", ") || "Your designated signer"} can sign and approve.`;
  const text = [`Hello ${name},`, `Your proposal is ready for review and authorization. Please click here to open your quote: ${d.link}`, ...(viewOnly ? [viewOnly] : []), ...(msg ? [msg] : []), `Thanks,\n\n${rep}`].join("\n\n");
  const esc = (t: string) => t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  const p = (t: string) => `<p style="margin:0 0 14px">${esc(t).replace(/\n/g, "<br/>")}</p>`;
  const html = `<!doctype html><html><body style="background:#ffffff;font-family:Poppins,Arial,sans-serif;color:#221F20;line-height:1.5">`
    + p(`Hello ${name},`)
    + `<p style="margin:0 0 14px">Your proposal is ready for review and authorization. Please <a href="${esc(d.link)}" style="color:#142647;font-weight:600">click here</a> to open your quote.</p>`
    + (viewOnly ? `<p style="margin:0 0 14px;color:#666">${esc(viewOnly)}</p>` : "")
    + (msg ? p(msg) : "") + p("Thanks,") + p(rep);
  return { text, html };
}

/** Sections shown in a proposal/RFP/RFQ before signing. The MSA ("terms") is shown only at the sign-and-invoice step. */
export const proposalVisibleSections = <T extends { key: string }>(sections: T[]): T[] => sections.filter((s) => s.key !== "terms" && isSectionShown(s));

/** "What we handle" lists only the services selected on the quote (unique labels, in order). */
export function selectedServiceLabels(lines: { label: string }[]): string[] {
  return [...new Set(lines.map((l) => String(l.label ?? "").trim()).filter(Boolean))];
}

/**
 * Which MSA version (if any) the client must sign. A client signs the MSA once.
 * They sign again only when Harmonious assigns them a newer version (an agreement row not yet executed).
 */
export function msaRequirement(agreements: { msa_version_id: string; executed_at: string | null; created_at: string }[], currentPublishedId: string | null): string | null {
  const pending = [...agreements].filter((a) => !a.executed_at).sort((a, b) => b.created_at.localeCompare(a.created_at))[0];
  if (pending) return pending.msa_version_id;
  if (agreements.some((a) => a.executed_at)) return null;
  return currentPublishedId;
}
