export function defaultSections(kind: DocKind, direction: DocDirection): Section[] {
  const s = (key: string, title: string): Section => ({ key, title, body: "" });
  if (direction === "outbound") return [s("overview", "Overview"), s("scope", "Scope of work"), s("requirements", "Requirements"), s("timeline", "Timeline"), s("submission", "How to respond"), s("evaluation", "Evaluation criteria")];
  if (kind === "rfq") return [s("summary", "Summary"), s("pricing", "Pricing"), s("terms", "Terms"), s("about", "About Harmonious")];
  return [s("summary", "Executive summary"), s("needs", "Your needs"), s("approach", "Our approach"), s("services", "Services and pricing"), s("timeline", "Timeline"), s("about", "About Harmonious"), s("next", "Next steps")];
}

export const sectionsText = (sections: Section[]) =>
  sections.map((s) => `${s.title}\n${s.question ? `Question: ${s.question}\n` : ""}${s.body}`.trim()).join("\n\n");

/** Fallback About Harmonious wording, used only until Marketing saves the controlled version. */
export const ABOUT_HARMONIOUS =
  "Harmonious is a fund administration and back-office platform for venture funds, SPVs and their investors. Our services span fund setup, investor onboarding and KYC, accounting and NAV, K-1 tax, regulatory filings, banking and cap tables.\n\nWe help fund teams coordinate administrative workflows and investor-related operations, with every engagement tailored to the services agreed during scoping.\n\nLearn more at harmonious.co.";

export type LockFacts = { about?: string | null; organization: string | null; contactName: string | null; lines: { label: string; quantity: number; unit_cents: number; line_cents: number; billing_frequency?: string | null }[] };

/** Sections whose text is generated by the platform and can't be edited (responses to prospects only). */
export function lockedKeys(kind: DocKind, direction: DocDirection): string[] {
  if (direction !== "response") return [];
  return kind === "rfq" ? ["summary", "pricing", "about"] : ["summary", "about"];
}

const money = (c: number) => `$${(Number(c) / 100).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const FREQ_WORD: Record<string, string> = { one_time: "one-time", monthly: "per month", quarterly: "per quarter", annual: "per year" };

export const SUMMARY_NOTE_TITLE = "Note from your Harmonious contact";
export const SUMMARY_NOTE_MAX = 300;

export function pricingText(lines: LockFacts["lines"]): string {
  if (!lines.length) return "Pricing will appear here once services are added to the quote.";
  const rows = lines.map((l) => `- ${l.label}: ${l.quantity} x ${money(l.unit_cents)} = ${money(l.line_cents)}${l.billing_frequency && FREQ_WORD[l.billing_frequency] ? ` ${FREQ_WORD[l.billing_frequency]}` : ""}`);
  const total = lines.reduce((s, l) => s + Number(l.line_cents || 0), 0);
  return `${rows.join("\n")}\nTotal: ${money(total)}\n(Pricing from the approved quote.)`;
}

export function summaryText(f: LockFacts): string {
  const services = f.lines.map((l) => l.label);
  const list = services.length <= 1 ? services[0] ?? "fund administration services" : `${services.slice(0, -1).join(", ")} and ${services[services.length - 1]}`;
  return `Harmonious proposes ${list} for ${f.organization || "your organization"}${f.contactName ? `, prepared for ${f.contactName}` : ""}.`;
}

/** Overwrites controlled sections with platform text; strips typed prices from editable sections. */
export function applyLockedSections(kind: DocKind, direction: DocDirection, sections: Section[], f: LockFacts): Section[] {
  const keys = lockedKeys(kind, direction);
  if (!keys.length) return sections;
  const gen: Record<string, string> = { summary: summaryText(f), pricing: pricingText(f.lines), about: f.about || ABOUT_HARMONIOUS };
  const out = sections.map((s) => {
    if (keys.includes(s.key)) return { ...s, body: gen[s.key] ?? s.body };
    if (kind !== "rfq" && s.key === "services") {
      const typed = s.body.split("\n").filter((l) => !/\$\s?[\d,]/.test(l) && !/^\s*Total:/i.test(l) && !/Pricing from the approved quote/i.test(l)).join("\n").trim();
      return { ...s, body: `${typed}\n\n${pricingText(f.lines)}`.trim() };
    }
    return s;
  });
  // Reps may add one short note under the summary; it's editable and still goes through approval.
  if (keys.includes("summary")) {
    const idx = out.findIndex((s) => s.key === "summary_note");
    const note = idx >= 0 ? { ...out.splice(idx, 1)[0]!, title: SUMMARY_NOTE_TITLE } : { key: "summary_note", title: SUMMARY_NOTE_TITLE, body: "" };
    note.body = note.body.replace(/\s+/g, " ").trim().slice(0, SUMMARY_NOTE_MAX);
    const at = out.findIndex((s) => s.key === "summary");
    out.splice(at >= 0 ? at + 1 : 0, 0, note);
  }
  for (const k of keys) if (!out.some((s) => s.key === k)) out.push({ key: k, title: k === "about" ? "About Harmonious" : k === "pricing" ? "Pricing" : "Summary", body: gen[k] ?? "" });
  return out;
}
